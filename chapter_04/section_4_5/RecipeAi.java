package chapter_04.section_4_5;

/*
 * 料理の手順を上から順番に表示するプログラムです。
 */
public class RecipeAi {
    public static void main(String[] args) {
        // 料理の手順を順番に表示します。
        System.out.println("1. 野菜を切る"); // 最初に野菜を準備します。
        System.out.println("2. 肉と野菜を炒める");
        System.out.println("3. 水を入れて煮込む");
        System.out.println("4. ルウを溶かす");
    }
}
